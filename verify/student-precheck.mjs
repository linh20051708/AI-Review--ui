import assert from "node:assert/strict"
import { register } from "node:module"
register("./self-service-loader.mjs", import.meta.url)
const storage = new Map()
globalThis.localStorage = { getItem:k=>storage.get(k)??null, setItem:(k,v)=>storage.set(k,v), removeItem:k=>storage.delete(k) }
const { studentPrecheck } = await import("../src/lib/studentPrecheck.ts")
const { personaTemplate } = await import("../src/lib/rubric.ts")
const { getReviewState } = await import("../src/data/reviewStore.ts")
const before = JSON.stringify(getReviewState()), persisted = JSON.stringify([...storage])
const rule = structuredClone(personaTemplate)
const result = await studentPrecheck(rule, new AbortController().signal)
assert.equal(result.evaluationStatus,"completed")
assert.equal(result.reviewId,"")
assert.ok(result.criterionResults.length)
assert.ok(result.criterionResults.every(c=>c.needsVerification))
assert.deepEqual(rule,personaTemplate)
await assert.rejects(studentPrecheck({...rule,name:""},new AbortController().signal),/tên/)
const retry = await studentPrecheck(rule,new AbortController().signal)
assert.equal(retry.overallScore,result.overallScore)
const changedFile = new AbortController()
const stale = studentPrecheck(rule,changedFile.signal)
changedFile.abort()
await assert.rejects(stale,{name:"AbortError"})
const replacement = await studentPrecheck(rule,new AbortController().signal)
assert.equal(replacement.evaluationStatus,"completed")
assert.equal(JSON.stringify(getReviewState()),before)
assert.equal(JSON.stringify([...storage]),persisted)
console.log("PASS precheck success, invalid-rule error, retry, cancellation/file replacement, immutable rule, zero store/storage/version/request writes")
